def test_postgres_transaction_uses_advisory_lock_for_single_reading_timer():
    from lib import database

    events = []

    class Transaction:
        def __enter__(self):
            events.append('begin')
        def __exit__(self, *_):
            events.append('end')

    class PostgresConnection:
        backend = 'postgres'
        def transaction(self):
            return Transaction()
        def execute(self, query, params=()):
            events.append(query)

    with database.transaction(PostgresConnection(), lock_reading=True):
        events.append('work')

    assert events == [
        'begin',
        "SELECT pg_advisory_xact_lock(hashtext('bookbutler:reading-session'))",
        'work',
        'end',
    ]
